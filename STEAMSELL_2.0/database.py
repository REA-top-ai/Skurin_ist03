import os  # Импортируем стандартный модуль для работы с операционной системой (нужен для чтения .env)
from sqlalchemy import create_engine, Column, Integer, String, ForeignKey  # Импортируем инструменты создания подключения и типов колонок таблицы
from sqlalchemy.ext.declarative import declarative_base  # Импортируем функцию создания базового класса, от которого строятся модели таблиц
from sqlalchemy.orm import sessionmaker  # Импортируем фабрику для генерации сессий (сеансов связи) с базой данных
from dotenv import load_dotenv  # Импортируем функцию автоматической загрузки скрытых настроек из текстового файла .env

load_dotenv()  # Считываем конфигурационные переменные из файла .env и загружаем их в переменные окружения системы

db_url = os.getenv("DATABASE_URL")  # Извлекаем из системы строковый адрес подключения к базе данных (например, хост, логин, пароль)

if not db_url:  # Проверяем предохранителем: если переменная db_url оказалась пустой (строка подключения отсутствует)
    raise ValueError("КРИТИЧЕСКАЯ ОШИБКА: Переменная окружения DATABASE_URL не установлена!")  # Останавливаем сервер и выкидываем ошибку

if db_url.startswith("postgres://"):  # Костыль для совместимости: если строка подключения начинается со старого префикса "postgres://"
    db_url = db_url.replace("postgres://", "postgresql://", 1)  # Заменяем его на корректный для SQLAlchemy префикс "postgresql://" (1 раз)


engine = create_engine(db_url)  # Создаем объект "движка" SQLAlchemy — главный узел, который управляет пулом соединений с PostgreSQL
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)  # Настраиваем класс локальных сессий (без автокоммита и автосброса, привязав к engine)
Base = declarative_base()  # Создаем родительский (декларативный) класс, который будет автоматически собирать структуру таблиц из наших моделей


def get_db():  # Объявляем функцию-генератор get_db для управления сессиями базы данных при каждом запросе
    db = SessionLocal()  # Создаем живой изолированный сеанс (сессию) транзакции с базой данных PostgreSQL
    try:  # Открываем защищенный блок try-finally для гарантированного закрытия соединения
        yield db  # Временно отдаем созданную сессию db в функцию контроллера FastAPI, приостанавливая выполнение здесь
    finally:  # Этот блок выполнится ВСЕГДА после того, как FastAPI закончит обрабатывать сетевой запрос пользователя
        db.close()  # Закрываем сессию и возвращаем соединение обратно в пул движка engine, предотвращая утечку памяти


class User(Base):  # Объявляем модель таблицы пользователей User, наследуясь от декларативного базового класса Base
    __tablename__ = "users"  # Явно указываем SQLAlchemy, что физическая таблица в базе данных PostgreSQL будет называться "users"

    id = Column(Integer, primary_key=True, index=True)  # Определяем колонку ID: тип — целое число, является первичным уникальным ключом, индексируется
    username = Column(String, unique=True, index=True)  # Определяем колонку логина: строковый тип, значение должно быть уникальным во всей БД, индексируется
    steam_id = Column(String, unique=True, index=True, nullable=True)  # Определяем поле SteamID: строка, уникально, индексируется, может быть пустым (nullable=True)
    hashed_password = Column(String, nullable=True)  # Определяем поле для хэша пароля: строковый тип, может быть пустым (для вошедших чисто через Steam)


def init_db():  # Объявляем функцию инициализации базы данных при старте веб-сервера
    # Создает таблицы в PostgreSQL, если их еще нет
    Base.metadata.create_all(bind=engine)  # Сканирует все классы-наследники Base (например, User) и физически создает их таблицы в PostgreSQL через движок engine